/** 話者IDからキャラクターを引く（未指定・不明ならモジカ）。 */
export function characterOf(id: string | undefined): CharacterDef {
  return CHARACTERS[id as SpeakerId] ?? CHARACTERS.mojika;
}

/** 表情に合った顔アイコンを返す（差分がないキャラ・通常時は通常の顔）。 */
export function faceFor(character: CharacterDef, mood?: 'smile' | 'sad'): string {
  if (mood === 'smile') return character.faceSmile ?? character.face;
  if (mood === 'sad') return character.faceSad ?? character.face;
  return character.face;
}

/** 表情に合った立ち絵を返す（差分がないキャラ・通常時は通常の立ち絵）。 */
export function imageFor(character: CharacterDef, mood?: 'smile' | 'sad'): string {
  if (mood === 'smile') return character.imageSmile ?? character.image;
  if (mood === 'sad') return character.imageSad ?? character.image;
  return character.image;
}

/** 立ち絵のsrcset（ブラウザが画面幅・解像度に合う方を選ぶ）。 */
export function imageSrcSet(character: CharacterDef, mood?: 'smile' | 'sad'): string {
  const lg = imageFor(character, mood);
  const sm = (mood === 'smile' ? character.imageSmileSm : mood === 'sad' ? character.imageSadSm : character.imageSm) ?? lg;
  return sm === lg ? lg : `${sm} 360w, ${lg} 720w`;
}

/** 顔アイコンのsrcset。 */
export function faceSrcSet(character: CharacterDef, mood?: 'smile' | 'sad'): string {
  const lg = faceFor(character, mood);
  const sm = (mood === 'smile' ? character.faceSmileSm : mood === 'sad' ? character.faceSadSm : character.faceSm) ?? lg;
  return sm === lg ? lg : `${sm} 128w, ${lg} 256w`;
}
